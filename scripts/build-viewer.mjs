/**
 * Builds the trip viewer into ONE self-contained HTML file (no internet needed to open it).
 *
 * Output:
 *   dist/njia-viewer.html          -> open this on a PC to view trip files
 *   src/generated/viewerHtml.ts    -> the same page, embedded inside the phone app
 *
 * Run with:  npm run build:viewer   (also runs automatically after npm install)
 */
import { build } from 'esbuild';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf8');

const result = await build({
  entryPoints: [join(root, 'viewer/src/main.ts')],
  bundle: true,
  format: 'iife',
  target: ['chrome80'],
  minify: true,
  write: false,
  legalComments: 'none',
});
const appJs = result.outputFiles[0].text;

// A literal "</script>" inside inlined code would end the script tag early.
const safe = (code) => code.replace(/<\/script/gi, '<\\/script');

const template = read('viewer/template.html');
const parts = {
  '/*__MAPLIBRE_CSS__*/': read('node_modules/maplibre-gl/dist/maplibre-gl.css'),
  '/*__MAPLIBRE_JS__*/': safe(read('node_modules/maplibre-gl/dist/maplibre-gl.js')),
  '/*__APP_JS__*/': safe(appJs),
};

let html = template;
for (const [marker, content] of Object.entries(parts)) {
  if (!html.includes(marker)) throw new Error(`Template is missing the marker ${marker}`);
  // split/join instead of replace(): the content contains "$" characters.
  html = html.split(marker).join(content);
}
if (!html.includes('/*__NJIA_DATA__*/')) throw new Error('Template is missing the data marker');

mkdirSync(join(root, 'dist'), { recursive: true });
mkdirSync(join(root, 'src/generated'), { recursive: true });
writeFileSync(join(root, 'dist/njia-viewer.html'), html);
writeFileSync(
  join(root, 'src/generated/viewerHtml.ts'),
  '// GENERATED by scripts/build-viewer.mjs. Do not edit by hand.\n' +
    `export const VIEWER_HTML: string = ${JSON.stringify(html)};\n` +
    "export const DATA_MARKER = '/*__NJIA_DATA__*/';\n"
);

console.log(`Viewer built: ${(html.length / 1024).toFixed(0)} KB`);
